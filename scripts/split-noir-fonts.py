"""Split each Noir font face into a small "core" file and a larger "rest" file.

The core holds every non-Han character the fonts cover plus the Han characters
the town player surface actually shows (UI, world, cases). The rest holds the
other Han characters. fonts.css gives each file a unicode-range, so a browser
downloads the rest only when a page renders one of its characters (older
pages, or a rare character typed into the notes).

Run from the project root after editing case text or town UI copy:
  python scripts/split-noir-fonts.py

Inputs (local, not in git): outputs/noir-font-subset/originals/*.ttf, the
charset.txt the full subset was built from, and Brotli in python-deps.
"""
from pathlib import Path
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
TOOL = ROOT / 'outputs/noir-font-subset'
PUBLIC = ROOT / 'public/fonts/noir'
sys.path.insert(0, str(TOOL / 'python-deps'))
from fontTools import subset  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402

# Everything the town player can see. Keep in step with the town-play route.
CORE_SOURCES = [
    'app/town-play', 'app/layout.tsx', 'app/localization', 'lib/world', 'lib/town-play-contract.ts',
    'packages/engine/src/cases', 'packages/engine/src/riverbend-case.ts', 'packages/engine/src/riverbend-world.ts',
    'packages/engine/src/case-pack.ts', 'world-packs',
]
EXTENSIONS = {'.ts', '.tsx', '.js', '.mjs', '.json', '.css'}
FACES = [
    ('Noto Sans SC', 400, '16614f6ffef6141858.ttf', 'noir-sans-sc-regular'),
    ('Noto Sans SC', 600, 'a9fb3edf8ec6199047.ttf', 'noir-sans-sc-semibold'),
    ('Noto Serif SC', 400, 'c5d53f3aebe1280769.ttf', 'noir-serif-sc-regular'),
    ('Noto Serif SC', 600, 'eeb9ac3e6b8797aadb.ttf', 'noir-serif-sc-semibold'),
]


HAN_RANGE = 'U+3400-9FFF, U+F900-FAFF, U+20000-3FFFF'


def is_han(point):
    return 0x3400 <= point <= 0x9FFF or 0xF900 <= point <= 0xFAFF or 0x20000 <= point <= 0x3FFFF


def scan(paths):
    points = set()
    for name in paths:
        base = ROOT / name
        files = [base] if base.is_file() else [p for p in base.rglob('*') if p.suffix in EXTENSIONS]
        for file in files:
            text = file.read_text(encoding='utf-8', errors='ignore')
            points.update(ord(c) for c in text)
            # Characters written as \uXXXX escapes in source.
            points.update(int(h, 16) for h in re.findall(r'\\u([0-9a-fA-F]{4})', text))
    return points


def build(source, points, target):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.name_legacy = True
    options.name_languages = ['*']
    options.notdef_glyph = True
    options.notdef_outline = True
    options.recalc_timestamp = False
    font = TTFont(source)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=points)
    subsetter.subset(font)
    font.flavor = 'woff2'
    font.save(target)
    return target.stat().st_size


def main():
    full = {ord(c) for c in (TOOL / 'charset.txt').read_text(encoding='utf-8') if c not in '\r\n'}
    used = scan(CORE_SOURCES)
    # Han characters the town uses go in the core even when the older full
    # charset missed them (names added by later cases, for example).
    core = {p for p in full if not is_han(p)} | {p for p in used if is_han(p)}
    rest = {p for p in full if is_han(p)} - core
    css, report = [], []
    for family, weight, ttf, stem in FACES:
        source = TOOL / 'originals' / ttf
        cmap = TTFont(source).getBestCmap()
        parts = [('core', {p for p in core if p in cmap}), ('rest', {p for p in rest if p in cmap})]
        # Rest first, core second: overlapping faces are tried in reverse order,
        # so the core is always asked first and the rest is fetched only for a
        # character the core lacks. Broad ranges keep this stylesheet tiny.
        for part, points in reversed(parts):
            name = f'{stem}.{part}.woff2'
            size = build(source, points, PUBLIC / name)
            report.append({'file': name, 'codepoints': len(points), 'bytes': size})
            unicode_range = f"\n  unicode-range: {HAN_RANGE};" if part == 'rest' else ''
            css.append(
                f"@font-face {{\n  font-family: '{family}';\n  font-style: normal;\n  font-weight: {weight};\n"
                f"  font-display: swap;\n  src: url('/fonts/noir/{name}') format('woff2');{unicode_range}\n}}\n"
            )
        old = PUBLIC / f'{stem}.woff2'
        if old.exists():
            old.unlink()
    header = '/* Generated by scripts/split-noir-fonts.py. Each face is split in two; the rest file loads only when needed. */\n\n'
    (PUBLIC / 'fonts.css').write_text(header + '\n'.join(css), encoding='utf-8')
    sources = json.loads((PUBLIC / 'sources.json').read_text(encoding='utf-8'))
    sources['split'] = {
        'script': 'scripts/split-noir-fonts.py',
        'coreSources': CORE_SOURCES,
        'coreHan': len([p for p in core if is_han(p)]),
        'restHan': len(rest),
        # Read by scripts/check-cases.mjs to warn when new case text needs a rebuild.
        'coreHanChars': ''.join(chr(p) for p in sorted(core) if is_han(p)),
        'files': report,
    }
    (PUBLIC / 'sources.json').write_text(json.dumps(sources, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    for row in report:
        print(f"{row['file']:40} {row['codepoints']:6} chars {row['bytes'] / 1024:8.1f} KB")


if __name__ == '__main__':
    main()
