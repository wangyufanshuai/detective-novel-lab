const SYSTEM_MESSAGE_ZH = Object.fromEntries(
  (Object.keys(EN_MESSAGES) as Array<keyof typeof EN_MESSAGES>).map((key) => [EN_MESSAGES[key], ZH_MESSAGES[key]])
) as Record<string, string>;

const SYSTEM_MESSAGE_EN = Object.fromEntries(
  (Object.keys(EN_MESSAGES) as Array<keyof typeof EN_MESSAGES>).map((key) => [ZH_MESSAGES[key], EN_MESSAGES[key]])
) as Record<string, string>;

const FORBIDDEN_LOCALE_OUTPUT = /\b(?:culpritId|victimId|caseId|sessionId|worldId|npcId|sourceId|eventId|hiddenTruth|rawBody)\b|[A-Za-z]:[\\/]/i;

export function isAppLocale(value: unknown): value is AppLocale {
  return value === "zh-CN" || value === "en-US";
}

export function formatLocaleMessage(locale: AppLocale, key: LocaleMessageKey, variables: LocaleVariables = {}) {
  const template = (locale === "zh-CN" ? ZH_MESSAGES : EN_MESSAGES)[key] || EN_MESSAGES[key];
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}

export function localizePublicText(value: string, locale: AppLocale) {
  if (!value) return value;
  const dictionary = locale === "zh-CN" ? SAFE_CONTENT_ZH : SAFE_CONTENT_EN;
  const exact = (locale === "zh-CN" ? SYSTEM_MESSAGE_ZH : SYSTEM_MESSAGE_EN)[value] || dictionary[value];
  if (exact) return exact;
  return value.replace(/[^/·→]+/g, (segment) => {
    const leading = segment.match(/^\s*/)?.[0] || "";
    const trailing = segment.match(/\s*$/)?.[0] || "";
    const core = segment.trim();
    return `${leading}${dictionary[core] || core}${trailing}`;
  });
}

export function localizeSafeTree<T>(value: T, locale: AppLocale): T {
  if (typeof value === "string") return localizePublicText(value, locale) as T;
  if (Array.isArray(value)) return value.map((item) => localizeSafeTree(item, locale)) as T;
  if (!value || typeof value !== "object") return value;
  return Object.fromEntries(Object.entries(value).map(([key, nested]) => [key, localizeSafeTree(nested, locale)])) as T;
}

export function validateLocaleCatalog() {
  const missing = (Object.keys(EN_MESSAGES) as LocaleMessageKey[]).filter((key) => !ZH_MESSAGES[key]);
  const unsafe = (Object.keys(EN_MESSAGES) as LocaleMessageKey[]).filter((key) => FORBIDDEN_LOCALE_OUTPUT.test(`${EN_MESSAGES[key]} ${ZH_MESSAGES[key]}`));
  return { ok: missing.length === 0 && unsafe.length === 0, missing, unsafe, keyCount: Object.keys(EN_MESSAGES).length };
}

export function localeCatalogSnapshot(locale: AppLocale): Readonly<Record<LocaleMessageKey, string>> {
  return locale === "zh-CN" ? { ...ZH_MESSAGES } : { ...EN_MESSAGES };
}
